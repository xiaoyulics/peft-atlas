"""Figure "rebase" (Expose V): what merge-and-restart can reach (Thm V.3 and its corollaries 1, 2 and 4).

A port of site/js/fig-rebase.js (tabs A and B of the rebasing-reach explorer) and of checks 12q and 12t of
theory/framework_checks.py (butterfly hypergraph components, Lie closure of block-orthogonal factors).

Everything is float64 and seeded with the site's mulberry32 generator.

(a) Rank staircase (Thm V.3(a), Cor 1, Cor 2). W0 in R^{24x16} is injective with singular values 2 -> 0.5 evenly spaced.
    ReLoRA adds a fresh random rank-r product B_k A_k each cycle (B_k with N(0,1) entries, A_k with N(0, 1/n) entries);
    the rank of the accumulated update sum_k B_k A_k is measured by an SVD (tolerance 1e-9 sigma_1, floor 1e-12) and
    compared with min(K r, m, n). LoRA-XS with frames frozen at W0 updates U_r R_k V_r^T (R_k with N(0, 1/r^2)
    entries, the site's default update size): its accumulated update keeps rank r (idempotent, Cor 2).

(b) Block-orthogonal factors on n = 16 coordinates (Thm V.3(b), (c), Cor 4). Each factor family is a set of coordinate
    blocks I_j (block OFT: a fixed partition; BOFT with block size b and m' butterfly factors: level l pairs half-block
    c with c XOR 2^l; Givens: planes {i, j}). Union-find gives the components C of the hypergraph, and
    dim Lie<so(I_j)> = sum_C C(|C|, 2) (Thm V.3(c)). Two independent measurements confirm each value:
      Lie closure    the dimension of the Lie algebra generated by the plane rotations spanning the so(I_j),
                     by repeated brackets (as in check 12t of framework_checks.py);
      reach          dim R_K, the rank of the right-trivialised Jacobian of the K-cycle product of exact-Cayley factors
                     F = (I + Q)(I - Q)^{-1} at a random point (the site's jacDims), for K = 1..16 merge cycles.
    The bars show dim R_1 (one cycle) and dim R_16 = dim Lie<so(I_j)> against dim so(16) = 120.

Run from paper/figures/src:  python3 fig_rebase.py
"""
import math
import warnings

import numpy as np
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
