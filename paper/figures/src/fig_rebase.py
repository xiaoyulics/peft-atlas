def fit_width(fig, width, iters=5):
    """Rescale the figure so that its tight bounding box (what save() writes) is exactly `width` inches wide."""
    for _ in range(iters):
        fig.canvas.draw()
        bb = fig.get_tightbbox(fig.canvas.get_renderer())
        w = bb.width + 2 * plt.rcParams['savefig.pad_inches']
        if abs(w - width) < 1e-3:
            break
        fw, fh = fig.get_size_inches()
        fig.set_size_inches(fw * width / w, fh * width / w)


def panel_label(ax, s, x, y=1.0, transform=None):
    ax.text(x, y, s, transform=transform or ax.transAxes, fontsize=9, fontweight='medium', color=C['ink'],
            va='bottom', ha='left')


COMP_COLORS = [C['blue'], C['orange'], C['green'], C['vermillion'], C['sky'], C['purple'], C['yellow']]


