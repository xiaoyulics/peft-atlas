M32 = 0xFFFFFFFF
# NumPy 2.0 with Apple Accelerate raises spurious floating-point warnings inside matmul even when every product is
# exact and finite; silence only those (the asserts below check every result)
warnings.filterwarnings('ignore', message='.*encountered in matmul', category=RuntimeWarning)


class Rng:
    """The site's seeded generator (site/js/core.js: Atlas.rng, mulberry32 + Box-Muller)."""

    def __init__(self, seed):
        self.a = (seed & M32) or 1

    def __call__(self):
        self.a = (self.a + 0x6D2B79F5) & M32
        a = self.a
        t = ((a ^ (a >> 15)) * (1 | a)) & M32
        t = ((t + (((t ^ (t >> 7)) * (61 | t)) & M32)) & M32) ^ t
        return ((t ^ (t >> 14)) & M32) / 4294967296

    def normal(self):
        u = 0.0
        while u == 0:
            u = self()
        v = 0.0
        while v == 0:
            v = self()
        return math.sqrt(-2 * math.log(u)) * math.cos(2 * math.pi * v)

    def randn(self, m, n, scale=1.0):
        """LA.randn: row-major draws."""
        return np.array([[self.normal() * scale for _ in range(n)] for _ in range(m)])


M, N = 24, 16
DIM_SO = N * (N - 1) // 2                       # 120
RTOL, ATOL = 1e-9, 1e-12
SIG = [2 - 1.5 * i / (N - 1) for i in range(N)]
UPD = 1.0                                       # LoRA-XS update size E||R_k||_F (the site's default)
KMAX = 8
RS = [3, 5]                                     # ReLoRA ranks shown
R_XS = 5                                        # LoRA-XS (frozen frame) rank shown
KB = 16                                         # merge cycles for the reach measurement


def rank(X):
    s = np.linalg.svd(X, compute_uv=False)
    tol = max(RTOL * s[0], ATOL)
    return int(np.sum(s > tol))


def orth_cols(m, n, rnd):
    """m x n with orthonormal columns (Gram-Schmidt twice), drawn column by column as on the site."""
    cols = []
    for _ in range(n):
        v = np.array([rnd.normal() for _ in range(m)])
        for _ in range(2):
            for c in cols:
                v -= (v @ c) * c
        cols.append(v / np.linalg.norm(v))
    return np.array(cols).T


def base():
    rnd = Rng(20261001)
    U, V = orth_cols(M, N, rnd), orth_cols(N, N, rnd)
    W0 = U @ np.diag(SIG) @ V.T
    return W0


# ---------------------------------------------------------------------------------------------------------------
# (a) additive rebasing
# ---------------------------------------------------------------------------------------------------------------
def run_a(W0, r, upd=UPD, seed=1, Kmax=KMAX):
    rA, rX = Rng(1000 + 31 * seed + r), Rng(5000 + 31 * seed + r)
    U, s, Vt = np.linalg.svd(W0, full_matrices=False)
    U0, V0 = U[:, :r], Vt[:r].T
    D, Df = np.zeros((M, N)), np.zeros((M, N))
    out = dict(r=r, relora=[0], bound=[0], xsF=[0])
    for k in range(1, Kmax + 1):
        B = rA.randn(M, r)
        A = rA.randn(r, N, 1 / math.sqrt(N))
        D = D + B @ A
        out['relora'].append(rank(D))
        out['bound'].append(min(k * r, M, N))
        R = rX.randn(r, r, upd / r)                 # E ||R_k||_F^2 = upd^2
        Df = Df + U0 @ R @ V0.T
        out['xsF'].append(rank(Df))
    out['Kstar'] = math.ceil(min(M, N) / r)
    return out


