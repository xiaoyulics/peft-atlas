                    ax.plot([lo, hi], [yb, yb], color=C['ink3'], lw=0.6, zorder=1)
                    for j in I:
                        ax.plot([j, j], [yb, y0 - 0.1], color=C['ink3'], lw=0.5, zorder=1)
