# (b) block-orthogonal factors
# ---------------------------------------------------------------------------------------------------------------
def contiguous(b):
    return [list(range(s, s + b)) for s in range(0, N, b)]


def butterfly_level(b, l):
    """BOFT factor at level l with block size b: half-blocks of size b/2, half-block c paired with c XOR 2^l."""
    hh, H = b // 2, N // (b // 2)
    out = []
    for c in range(H):
        c2 = c ^ (1 << l)
        if c < c2 < H:
            out.append(list(range(c * hh, c * hh + hh)) + list(range(c2 * hh, c2 * hh + hh)))
    return out


GIVENS7 = [[0, 1], [1, 5], [5, 6], [9, 10], [10, 14], [3, 12], [7, 8]]             # the site's default planes
GIVENS15 = GIVENS7 + [[6, 9], [2, 3], [4, 5], [8, 11], [12, 13], [14, 15], [11, 13], [10, 12]]   # a spanning tree

FAMILIES = [   # (group, parameter label, list of factors; each factor is a list of disjoint blocks)
    ('block OFT', r'$b=4$', [contiguous(4)]),
    ('block OFT', r'$b=8$', [contiguous(8)]),
    ('BOFT, $b=2$', r"$m′=2$", [butterfly_level(2, l) for l in range(2)]),
    ('BOFT, $b=2$', r"$m′=3$", [butterfly_level(2, l) for l in range(3)]),
    ('BOFT, $b=2$', r"$m′=4$, full depth", [butterfly_level(2, l) for l in range(4)]),
    ('Givens', '7 planes', [[p] for p in GIVENS7]),
    ('Givens', '15 planes, a tree', [[p] for p in GIVENS15]),
]


def components(factors):
    par = list(range(N))

    def find(x):
        while par[x] != x:
            par[x] = par[par[x]]
            x = par[x]
        return x
    for f in factors:
        for I in f:
            for t in I[1:]:
                a, c = find(I[0]), find(t)
                if a != c:
                    par[c] = a
    roots, lab, sizes = {}, [], []
    for i in range(N):
        rt = find(i)
        if rt not in roots:
            roots[rt] = len(sizes)
            sizes.append(0)
        lab.append(roots[rt])
        sizes[roots[rt]] += 1
    return dict(lab=lab, sizes=sizes, lie=sum(s * (s - 1) // 2 for s in sizes))


def generators(factors):
    """A basis of every so(I_j): the plane rotations L_ac = E_ac - E_ca for a < c in a block I_j."""
    out = []
    for f in factors:
        for I in f:
            for a in range(len(I)):
                for c in range(a + 1, len(I)):
                    L = np.zeros((N, N))
                    L[I[a], I[c]], L[I[c], I[a]] = 1.0, -1.0
                    out.append(L)
    return out


def lie_closure(gens, tol=1e-8):
    """Dimension of the Lie algebra generated by gens (check 12t of framework_checks.py): add brackets until closed."""
    basis = []

    def add(Mx):
        v = Mx.ravel()
        res = v - (np.array(basis).T @ (np.array(basis) @ v) if basis else 0)
        if np.linalg.norm(res) > tol * max(1.0, np.linalg.norm(v)):
            basis.append(res / np.linalg.norm(res))
            return True
        return False
    mats = [G for G in gens if add(G)]
    frontier = list(mats)
    while frontier:
        new = []
        for X in frontier:
            for Y in mats:
                Z = X @ Y - Y @ X
                if add(Z):
                    new.append(Z)
        mats += new
        frontier = new
    return len(basis)


def cayley(Q):
    I = np.eye(len(Q))
    return (I + Q) @ np.linalg.inv(I - Q)


def reach_dims(factors, seed=1, K=KB):
    """dim R_k, k = 1..K, for exact-Cayley factors (the site's jacDims, map = 'exact'). The right-trivialised tangent
    of (factors) -> F_1 ... F_P is spanned by T L_ac T^T, with T the product of the factors before F_j and L_ac the
    rotation generators of F_j's blocks (the Cayley map is a local diffeomorphism and T is orthogonal)."""
    rnd = Rng(4242 + seed)
    iu = np.triu_indices(N, 1)
    T = np.eye(N)
    vecs, dims = [], []
    for _ in range(K):
        for f in factors:
            for I in f:
                for a in range(len(I)):
                    for c in range(a + 1, len(I)):
                        X = np.outer(T[:, I[a]], T[:, I[c]])
                        vecs.append((X - X.T)[iu])
            Q = np.zeros((N, N))
            for I in f:                              # random skew generator on the factor's blocks (scale 0.3/sqrt b)
                sc = 0.3 / math.sqrt(len(I))
                for a in range(len(I)):
                    for c in range(a + 1, len(I)):
                        x = rnd.normal() * sc
                        Q[I[a], I[c]], Q[I[c], I[a]] = x, -x
            T = T @ cayley(Q)
        s = np.linalg.svd(np.array(vecs), compute_uv=False)
        dims.append(int(np.sum(s > 1e-8 * s[0])))
    return dims


def compute():
    W0 = base()
    s = np.linalg.svd(W0, compute_uv=False)
    print('W0: 24 x 16, rank %d, singular values %.3f .. %.3f' % (rank(W0), s[0], s[-1]))
    RA = {r: run_a(W0, r) for r in RS}
    if R_XS not in RA:
        RA[R_XS] = run_a(W0, R_XS)
    print('(a) rank of the accumulated update after K = 0..%d merge cycles' % KMAX)
    for r in sorted(RA):
        x = RA[r]
        print('   r = %d  ReLoRA %s  bound min(Kr, m, n) %s  K* = %d  | LoRA-XS frozen %s'
              % (r, x['relora'], x['bound'], x['Kstar'], x['xsF']))
        assert x['relora'] == x['bound'] and all(v == min(r, k * r) for k, v in enumerate(x['xsF']))

    print('(b) block-orthogonal factors on n = 16 coordinates')
    RB = []
    for grp, par, factors in FAMILIES:
        cp = components(factors)
        lc = lie_closure(generators(factors))
        dims = reach_dims(factors)
        ksat = next(k + 1 for k, d in enumerate(dims) if d == dims[-1])
        sizes = sorted(cp['sizes'], reverse=True)
        print('   %-12s %-22s components %-28s sum C(|C|,2) = %3d | Lie closure %3d | dim R_1 = %3d, dim R_16 = %3d '
              '(reached at K = %d)' % (grp.replace('$', ''), par.replace('$', ''), sizes, cp['lie'], lc, dims[0],
                                         dims[-1], ksat))
        assert lc == cp['lie'] == dims[-1]
        RB.append(dict(group=grp, par=par, factors=factors, comp=cp, lie=cp['lie'], closure=lc, dims=dims, ksat=ksat))
    return RA, RB


