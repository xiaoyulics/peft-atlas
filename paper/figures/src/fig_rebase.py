    ax.text(7.5, -0.82, 'factor blocks on 16 coordinates,\ndots coloured by component', fontsize=7, color=C['ink2'],
            ha='center', va='center', linespacing=1.05)
    panel_label(ax, '(b)', LX, YT, transform=ax.transData)

    # ---------------- (b) generated dimension against dim SO(16) ----------------
    ax = axR
    for i, row in enumerate(RB):
        y0 = i + 0.1
        full = row['lie'] == DIM_SO
        col = C['moss'] if full else C['tide']
        ax.add_patch(Rectangle((0, y0 - 0.21), row['lie'], 0.42, fc=col, alpha=0.32, lw=0, zorder=2))
        ax.add_patch(Rectangle((0, y0 - 0.21), row['dims'][0], 0.42, fc=col, lw=0, zorder=3))
        if full:
            ax.text(row['lie'] - 3, y0, str(row['lie']), fontsize=7, color=C['ink'], ha='right', va='center', zorder=4)
        else:
            ax.text(row['lie'] + 3, y0, str(row['lie']), fontsize=7, color=C['ink'], ha='left', va='center')
    ax.axvline(DIM_SO, color=C['ink2'], lw=0.7, ls=(0, (3, 2)), zorder=1)
    ax.text(DIM_SO + 5, 2.6, r'$\dim\,\mathrm{SO}(16)=120$', fontsize=7, color=C['ink2'], ha='left', va='center',
            rotation=90)
    ax.set_xlim(0, 140)
    ax.set_xticks([0, 60, 120])
    ax.set_xlabel('dimension', labelpad=1)
    ax.spines['left'].set_visible(False)
    ax.tick_params(axis='y', left=False, labelleft=False)
    ax.legend([Rectangle((0, 0), 1, 1, fc=C['tide'], lw=0), Rectangle((0, 0), 1, 1, fc=C['tide'], alpha=0.32, lw=0)],
              ['one cycle', 'merged'], loc='upper left', bbox_to_anchor=(0.0, 1.0), handlelength=1.0,
              handleheight=0.7, borderaxespad=0.0, labelspacing=0.15, handletextpad=0.4, fontsize=7)
    fit_width(fig, W1)
    return fig


